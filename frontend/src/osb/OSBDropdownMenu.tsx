import { cn } from '../lib/utils'

/**
 * Transplanted from shadcn/ui `dropdown-menu.tsx` (MIT, Radix variant via
 * the shadcn registry). Same Radix wiring as the dialog/sheet bases (focus
 * management, outside-press + Escape dismiss, Sub submenus, keyboard nav);
 * only the panel floats from a trigger instead of docking or centering.
 * Deliberate adaptations for OpenSiteBuilder, each marked ADAPT below:
 *
 * ADAPT-1 (icons): `Check` / `ChevronRight` / `Circle` from lucide-react are
 *   inlined with lucide's exact paths, so the published template needs no
 *   extra dependency.
 * ADAPT-2 (theme): shadcn's `bg-popover` / `border` / `bg-accent` tokens come
 *   from ambient CSS vars, which OSB does not have. Neutral slate bases live
 *   here; callers override colors through `className` (tailwind-merge),
 *   exactly how shadcn consumers customize.
 * ADAPT-3 (scope): checkbox/radio items ship for shadcn parity but OSB menus
 *   use plain items, labels, and submenus — no knobs expose the rest.
 *
 * This is the ONE menu copy the canvas renders and codegen publishes (see
 * OSB README: single source of truth — the dialog base lives at ./OSBDialog
 * and the sheet base at ./OSBSheet the same way).
 */

